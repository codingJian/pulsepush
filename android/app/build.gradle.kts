        compose = true
        // AGP 8 turns this off by default; DeviceUtils/Settings read
        // BuildConfig.VERSION_NAME / VERSION_CODE.
        buildConfig = true
    }
    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }
}

