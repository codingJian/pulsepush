// Release signing: read keystore.properties if present (project root first,
// then app/). Missing file must NOT break debug / unsigned builds.
val keystorePropsCandidates = listOf(
    rootProject.file("keystore.properties"),
    file("keystore.properties")
)
val keystorePropsFile = keystorePropsCandidates.firstOrNull { it.exists() }
val keystoreProps = Properties().apply {
    if (keystorePropsFile != null) {
        FileInputStream(keystorePropsFile).use { load(it) }
    }
}
val hasReleaseSigning = keystorePropsFile != null &&
    keystoreProps.getProperty("storeFile") != null &&
    keystoreProps.getProperty("storePassword") != null &&
    keystoreProps.getProperty("keyAlias") != null &&
    keystoreProps.getProperty("keyPassword") != null

